#!/usr/bin/env bash
# fw_check_capability.sh — forge-wiki 의 **capability 진입점** (DRAFT, uncommitted).
#
# 질문: «이 위키의 파생 인덱스(AUTO-INDEX)가 실제 파일 상태와 어긋났나».
# SPEC §4: "`fw check` is the CI gate: exit 1 on index drift."
#
# verdict enum (declared): 0=CLEAN 1=DRIFT 3=NO_TARGET 10=HARNESS_ERROR
#   3 은 원 CLI 가 exit 1 로 뭉개던 «여긴 위키가 아니다(INDEX.md 없음)» 를 분리한 값이다.
#   그 1 은 «드리프트» 가 아니라 «시작조차 안 함» 이고, 둘이 같은 값이면 호출자는
#   «안 돌았다» 를 «결함 있다» 로 읽는다.
#
# 정리 트랩 규율(FH degrade_probe_capability.sh 2026-08-11 사고 답습):
#   OWNED_TMP(내가 만든 것) 와 TARGET(스캔 대상) 을 다른 변수로 분리하고,
#   트랩은 OWNED_TMP 만 본다. OWNED_TMP 는 최초 대입 후 재대입하지 않는다.
set -o pipefail
REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
FW="$REPO_ROOT/bin/fw.py"
[ -r "$FW" ] || { echo "fw-check-probe: HARNESS_ERROR — fw.py 부재($FW)"; exit 10; }
command -v python3 >/dev/null 2>&1 || {
  echo "fw-check-probe: HARNESS_ERROR — python3 부재(대상 없음이 아니다)"; exit 10; }

OWNED_TMP="$(mktemp -d)"      # ← 내가 만든 것. 재대입 금지.
_cleanup() {
  case "$OWNED_TMP" in
    /tmp/*|/var/folders/*|/private/tmp/*) [ -d "$OWNED_TMP" ] && rm -rf "$OWNED_TMP" ;;
    *) echo "fw-check-probe: cleanup 거부 — OWNED_TMP 가 임시 경로가 아니다: $OWNED_TMP" >&2 ;;
  esac
}
trap _cleanup EXIT

# 답을 아는 위키 픽스처를 짓는다. $1 = drift 를 심을지 여부.
_fixture() {
  local d="$OWNED_TMP/wiki" drift="$1"
  mkdir -p "$d/notes"
  printf -- '---\ntype: note\ndescription: "first"\n---\n\nbody\n' > "$d/notes/alpha_2026-01-01.md"
  printf '# home\n\n<!-- AUTO-INDEX:START (generated by fw.py — do not hand-edit inside) -->\n<!-- AUTO-INDEX:END -->\n' \
    > "$d/INDEX.md"
  ( cd "$d" && python3 "$FW" sync --write >/dev/null 2>&1 )
  # sync 자체가 실패했으면 픽스처가 안 선 것이다 — 그건 대상 결함이 아니라 계기 결함이다.
  grep -q 'AUTO-INDEX:START' "$d/INDEX.md" || return 1
  if [ "$drift" = "yes" ]; then
    # 인덱스를 재생성하지 않고 파일을 하나 더 넣는다 = 파생값이 실제와 어긋난 상태
    printf -- '---\ntype: note\ndescription: "second"\n---\n\nbody\n' > "$d/notes/beta_2026-02-02.md"
  fi
  printf '%s' "$d"
}

MODE="${1:-}"
TARGET=""                     # ← 실제 위키 경로를 가리킬 수 있다. 절대 안 지운다.

case "$MODE" in
  --known-positive)   # 답을 아는 양성: 인덱스가 어긋난 위키
    TARGET="$(_fixture yes)" || { echo "fw-check-probe: HARNESS_ERROR — 픽스처 생성 실패"; exit 10; } ;;
  --known-negative)   # 답을 아는 음성: 방금 sync 한 깨끗한 위키
    TARGET="$(_fixture no)"  || { echo "fw-check-probe: HARNESS_ERROR — 픽스처 생성 실패"; exit 10; } ;;
  --target) TARGET="${2:?--target 은 경로가 필요하다}" ;;
  '')       TARGET="$REPO_ROOT" ;;
  *) echo "fw-check-probe: 알 수 없는 모드 '$MODE'"; exit 10 ;;
esac

[ -d "$TARGET" ] || { echo "fw-check-probe: NO_TARGET — 경로가 디렉토리가 아니다: $TARGET"; exit 3; }
# «위키가 아니다» 를 **먼저** 판정한다 — fw.py 는 INDEX.md 부재를 exit 1 로 내는데,
# 그 1 은 드리프트와 같은 값이다. 못 돌린 것을 결함으로 렌더하지 않는다.
if [ ! -f "$TARGET/INDEX.md" ] && [ ! -f "$TARGET/index.md" ]; then
  echo "fw-check-probe: NO_TARGET — INDEX.md 없음, 위키 루트가 아니다(드리프트 아님)"; exit 3
fi

out="$(cd "$TARGET" && python3 "$FW" check 2>&1)"; rc=$?   # verdict 는 직접 취한다
case "$rc" in
  0) echo "fw-check-probe: CLEAN — $out"; exit 0 ;;
  1)
    # exit 1 이 드리프트인지 «시작 실패»인지 stdout 으로 가른다. fw.py 의 sys.exit(str) 은
    # 메시지를 stderr 로 내고 1 을 반환한다 — 위에서 걸렀지만 두 번째 방벽을 둔다.
    if printf '%s' "$out" | grep -q '\[fw check\] DRIFT'; then
      echo "fw-check-probe: DRIFT — $out"; exit 1
    fi
    echo "fw-check-probe: HARNESS_ERROR — exit 1 인데 드리프트 판정문이 없다: $out"; exit 10 ;;
  *) echo "fw-check-probe: HARNESS_ERROR — fw.py 가 enum 밖 $rc 반환: $out"; exit 10 ;;
esac
